// AWJ Signature V3 — generates design-lab/signature/nav-icons.js from the Lucide icons already in web/node_modules.
// No runtime dependency: the output is a plain script holding the SVG children of each icon, verbatim from Lucide.
// Usage: node design-lab/signature/tools/gen-nav-icons.mjs
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const here = path.dirname(fileURLToPath(import.meta.url));
const lucide = path.resolve(here, '../../../web/node_modules/lucide-react');
const outFile = path.resolve(here, '../nav-icons.js');

// One icon per navigation item and group. Names are Lucide's own; meaning is documented in design-lab/signature/docs/AWJ-SIGNATURE-V3-NAV-ICONS-REPORT.md.
export const NAMES = [
  'layout-dashboard', 'file-plus-2', 'files', 'file-text', 'file-minus-2', 'file-input', 'clipboard-list', 'building-2',
  'boxes', 'package-check', 'clipboard-check', 'users', 'scroll-text', 'book-open-text', 'list-tree', 'landmark',
  'receipt-text', 'id-card', 'banknote', 'wrench', 'calendar-clock', 'fuel', 'cylinder', 'percent', 'shield-check', 'chart-column',
  // group icons (tablet rail) and shared actions — one Lucide family for the whole navigation
  'house', 'shopping-cart', 'truck', 'package', 'calculator', 'hard-hat', 'settings', 'hand-coins', 'flask-conical',
];

const version = JSON.parse(fs.readFileSync(path.join(lucide, 'package.json'), 'utf8')).version;
const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const attr = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const icons = {};
for (const name of NAMES) {
  const src = fs.readFileSync(path.join(lucide, 'dist/esm/icons', `${name}.js`), 'utf8');
  const body = src.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/);
  if (!body) throw new Error(`cannot parse Lucide icon ${name}`);
  const nodes = [...body[1].matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)];
  const declared = (body[1].match(/\[\s*"\w+",\s*\{/g) || []).length;
  if (!nodes.length || nodes.length !== declared) throw new Error(`Lucide icon ${name}: parsed ${nodes.length} of ${declared} elements`);
  icons[name] = nodes.map(([, tag, attrs]) => {
    const pairs = [...attrs.matchAll(/(\w+):\s*"([^"]*)"/g)].filter(([, k]) => k !== 'key');
    return `<${tag} ${pairs.map(([, k, v]) => `${attr(k)}="${esc(v)}"`).join(' ')}/>`;
  }).join('');
}
const out = `/* AWJ Signature V3 — navigation icons. GENERATED by design-lab/signature/tools/gen-nav-icons.mjs; do not edit by hand.
 * Source: lucide-react ${version} (https://lucide.dev), ISC License.
 * Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
 * All other copyright (c) for Lucide are held by Lucide Contributors 2022.
 * Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted,
 * provided that the above copyright notice and this permission notice appear in all copies. */
window.AWJ_NAV_ICONS = ${JSON.stringify(icons, null, 1)};
`;
fs.writeFileSync(outFile, out);
console.log(`nav icons: ${NAMES.length} from lucide-react ${version} → ${path.relative(path.resolve(here, '../../..'), outFile)}`);
