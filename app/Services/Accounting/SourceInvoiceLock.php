<?php

namespace App\Services\Accounting;

use App\Models\Invoice;
use App\Tenancy\BranchScope;
use Illuminate\Support\Facades\DB;

/**
 * ═══════════════════════════════════════════════════════════════
 *  AWJ-TAX-REM-02 — ترتيب الأقفال الموحّد للمستندات المرتبطة بفاتورة
 * ═══════════════════════════════════════════════════════════════
 *  كل مسار يستهلك من سقف فاتورةٍ واحدة (إشعار دائن، مرتجع API، مرتجع POS،
 *  استبدال POS) يجب أن يُسلسَل على **صف الفاتورة نفسه** قبل أن يقرأ المستهلَك
 *  ويكتب. والترتيب العام الوحيد المسموح به هو:
 *
 *      صف الفاتورة  ←  صف الفرع (مرساة ترقيم القيد/المستند والـidempotency)  ←  المستأجر
 *
 *  مساراتُ الإشعار والمرتجع بالـAPI تأخذ الفاتورة ثم تبلغ مرساة الفرع في
 *  `LedgerService`. أما POS فكان يأخذ صف الفرع أولاً (مفتاح الـidempotency) ثم
 *  لا يقفل الفاتورة إطلاقاً، فكان إشعارٌ ومرتجعُ POS على السطر نفسه يقرآن
 *  المتبقي ذاته ويُرحَّلان معاً. وإضافة قفل الفاتورة *بعد* صف الفرع كانت
 *  ستعكس الترتيب وتفتح انسداداً (Deadlock)؛ لذلك يُؤخذ هنا **قبل** أي قفل فرع،
 *  في أول المعاملة، فيصير الترتيب واحداً في المسارات كلها.
 *
 *  القفل إعادة-دخولي داخل المعاملة نفسها (مرتجع POS داخل استبدال POS يطلبه
 *  ثانيةً فلا يُكلّف شيئاً). وهو لا-op على SQLite. لا فاتورة بالمعرّف (أو معرّف
 *  مشوّه) ⇒ لا شيء يُقفل؛ والتحقق من المصدر يبقى مسؤولية المسار نفسه.
 *
 *  يجب أن يُستدعى داخل `DB::transaction`.
 */
final class SourceInvoiceLock
{
    public static function acquire(?string $invoiceId): void
    {
        if ($invoiceId === null || $invoiceId === '' || DB::transactionLevel() === 0) {
            return;
        }

        // مرجع مخزَّن: يُحلّ خارج عزل الفرع (المستأجر وحده يعزل) كمسارات المرتجع.
        BranchScope::reference(Invoice::class)->whereKey($invoiceId)->lockForUpdate()->first(['id']);
    }
}
