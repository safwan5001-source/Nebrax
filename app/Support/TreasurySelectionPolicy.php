<?php

namespace App\Support;

/**
 * سياسة اختيار الخزينة/الحساب البنكي عند **غياب** اختيار صريح (TREASURY-T3، قرار D-T3 — السياسة تُضبط ولا تُفرَض).
 *
 * الاختيار الصريح يتقدّم دائماً ولا يتأثر بالسياسة. الخيار (ج) من التدقيق (افتراضي لكل فرع/مستخدم) يحتاج مخططاً جديداً
 * ويبقى خارج هذه الشريحة عمداً؛ تُضاف قيمته هنا حين يُعتمد.
 */
enum TreasurySelectionPolicy: string
{
    /** السلوك القائم للسندات اليوم: الكيان الرئيسي (`is_main`) من النوع المطلوب. */
    case MainOfType = 'main_of_type';

    /** لا افتراضي: غياب الاختيار خطأ صريح. */
    case ExplicitRequired = 'explicit_required';
}
