import { newPhone, layout, WEB } from './lib.mjs';
import fs from 'node:fs';
const seed = JSON.parse(fs.readFileSync('/tmp/claude-0/e2e/seed.json', 'utf8'));
const { shift } = JSON.parse(fs.readFileSync('/tmp/claude-0/e2e/live-shift2.json', 'utf8'));
const shot = (page, n) => page.screenshot({ path: `/tmp/claude-0/e2e/shots/${n}.png`, fullPage: true });
const s = await newPhone('ar'); const { page, errors } = s;
await page.goto(WEB + '/fuel-stations/ops/login', { waitUntil: 'networkidle' });
await page.locator('input[name=employee_no]').fill(seed.pins.supervisor.employee_no);
await page.locator('input[name=pin]').fill(seed.pins.supervisor.pin);
await page.getByRole('button', { name: 'دخول' }).last().click();
await page.waitForFunction(() => document.body.innerText.includes('مساحة عمل'), null, { timeout: 20000 });
await page.waitForTimeout(1500);
await page.goto(`${WEB}/fuel-stations/ops/shifts/${shift}/review`, { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
await shot(page, '50-review2');
const txt = (await page.evaluate(() => document.body.innerText)).replace(/\s+/g,' ');
console.log('REVIEW2 collection part:', txt.match(/المطابقة التشغيلية.*?ملخص نقد/)?.[0]?.slice(0,300));
console.log('REVIEW2 required list:', txt.match(/المراجعات المطلوبة.*?سجل الوردية/)?.[0]);
const approve = page.getByRole('button', { name: 'اعتماد الوردية' });
console.log('approve disabled:', await approve.isDisabled());
await approve.click();
await page.getByRole('dialog').waitFor();
const cb = page.getByRole('dialog').getByRole('checkbox'); if (await cb.count()) await cb.check();
await page.getByRole('dialog').getByRole('button', { name: 'تأكيد الاعتماد' }).click();
await page.waitForTimeout(3000);
await shot(page, '51-approve-before-review');
console.log('AFTER EARLY APPROVE:', (await page.evaluate(() => document.body.innerText)).replace(/\s+/g,' ').slice(0, 600));
const st = await (await fetch('http://e2e-ui.awj.app:8000/api/fuel-stations/shifts/' + shift, { headers: { Authorization: 'Bearer ' + seed.tokens.owner, Accept: 'application/json' } })).json();
console.log('shift status in server after early approve:', st.data.status);
console.log('ERRORS', errors.filter(e=>!/reqfailed/.test(e)));
await s.b.close();
