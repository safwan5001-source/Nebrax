import { newPhone, layout, WEB } from './lib.mjs';
import fs from 'node:fs';
import { execSync } from 'node:child_process';
const seed = JSON.parse(fs.readFileSync('/tmp/claude-0/e2e/seed.json', 'utf8'));
const API = 'http://e2e-ui.awj.app:8000/api';
const q = (sql) => execSync(`psql -h /tmp -p 5433 -U postgres -d e2e_ui -t -A -c "${sql}"`).toString().trim();
const shot = (page, n) => page.screenshot({ path: `/tmp/claude-0/e2e/shots/${n}.png`, fullPage: true });
const s = await newPhone('ar'); const { page, ctx, errors } = s;
const posts = [];
page.on('request', r => { if (r.method() === 'POST' && r.url().startsWith(API)) posts.push(new URL(r.url()).pathname.replace(/[0-9a-f]{8}-[0-9a-f-]{27}/g, '{id}')); });
await page.goto(WEB + '/fuel-stations/ops/login', { waitUntil: 'networkidle' });
await page.locator('input[name=employee_no]').fill(seed.pins.seller.employee_no);
await page.locator('input[name=pin]').fill(seed.pins.seller.pin);
await page.getByRole('button', { name: 'دخول' }).last().click();
await page.waitForFunction(() => document.body.innerText.includes('مساحة عمل'), null, { timeout: 20000 });
await page.waitForTimeout(1500);
const approvedBefore = q("select count(*) from fuel_shifts");
// (أ) نقر مزدوج سريع على تأكيد فتح الوردية
await page.goto(WEB + '/fuel-stations/ops/shifts/open', { waitUntil: 'networkidle' });
await page.getByTestId('open-float').fill('500');
await page.getByRole('button', { name: 'مراجعة وفتح الوردية' }).click();
const confirm = page.getByRole('dialog').getByRole('button', { name: 'تأكيد فتح الوردية' });
await confirm.dblclick({ delay: 10 }).catch(() => {});
await page.waitForTimeout(3500);
console.log('A) shifts before/after double-tap:', approvedBefore, q("select count(*) from fuel_shifts"), '| POST /shifts/open calls:', posts.filter(p => p.endsWith('/shifts/open')).length);
const shiftId = q("select id from fuel_shifts where status='open'");
fs.writeFileSync('/tmp/claude-0/e2e/live-shift4.json', JSON.stringify({ shift: shiftId }));
// (ب) إعادة تحميل أثناء إدخال القراءة ← المسودة المحلية
await page.goto(`${WEB}/fuel-stations/ops/shifts/${shiftId}/readings/opening`, { waitUntil: 'networkidle' });
await page.waitForTimeout(2000);
const inputs = page.locator('[data-entry-input]');
await inputs.nth(0).fill('1060'); await inputs.nth(1).fill('9940');
await page.waitForTimeout(800);
await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
console.log('B) after reload values:', await inputs.nth(0).inputValue(), await inputs.nth(1).inputValue(), '| rows saved so far:', q(`select count(*) from fuel_shift_meter_readings where fuel_shift_id='${shiftId}'`));
await shot(page, '70-reload-draft');
console.log('B) draft notice:', (await page.evaluate(() => document.body.innerText)).replace(/\s+/g,' ').match(/ما كتبته محفوظ[^.]*\./)?.[0]);
// (ج) انقطاع الاتصال لحظة التأكيد
await page.getByRole('button', { name: /مراجعة وحفظ/ }).click();
await page.getByRole('dialog').waitFor();
await ctx.setOffline(true);
const before = posts.length;
await page.getByRole('dialog').getByRole('button', { name: 'تأكيد وحفظ' }).click();
await page.waitForTimeout(3500);
await shot(page, '71-offline-save');
const txt = (await page.evaluate(() => document.body.innerText)).replace(/\s+/g,' ');
console.log('C) offline message:', txt.match(/(قد يكون|تعذر|لا يوجد اتصال|فشل|تحقق)[^.]{0,160}\./)?.[0] ?? txt.slice(0, 300));
console.log('C) POST attempts while offline:', posts.length - before, '(لا إعادة تلقائية متوقعة = 2 للمحاولة، 1 كل قراءة)');
await ctx.setOffline(false);
await page.waitForTimeout(4000);
console.log('C) after back online, readings saved (no auto-retry expected unless user acts):', q(`select count(*) from fuel_shift_meter_readings where fuel_shift_id='${shiftId}'`), q(`select count(*) from fuel_shift_tank_readings where fuel_shift_id='${shiftId}'`));
console.log('C) buttons now:', await page.getByRole('button').allInnerTexts());
await shot(page, '72-back-online');
console.log('ERRORS', errors.filter(e=>!/reqfailed/.test(e)));
await s.b.close();
