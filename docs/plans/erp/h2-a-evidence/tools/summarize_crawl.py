#!/usr/bin/env python3
"""AWJ-ERP-UI-H2 A1 — summarize crawl.cjs JSONL into the H2 baseline matrix (evidence tooling).
Usage: python3 summarize_crawl.py <out.md> <label=results.jsonl> ...   (label e.g. v3a, v3b, legacy)"""
import json, re, sys
from collections import defaultdict
out, pairs = sys.argv[1], sys.argv[2:]
recs = []
for p in pairs:
    label, path = p.split('=', 1)
    rows = [json.loads(l) for l in open(path, encoding='utf-8') if l.strip()]
    if not rows: sys.exit(f'empty input {path}')
    for r in rows: r['_ui'] = label; recs.append(r)
cols = sorted({(r['_ui'], r['cfg']) for r in recs}, key=lambda c: (c[0].startswith('legacy'), c[1]))
by = defaultdict(list)
for r in recs: by[(r['_ui'], r['cfg'])].append(r)
FIXTURE_NAMES = ('المالك a', 'الفرع الرئيسي')
def arabic_left(t):
    if t == 'ع': return False
    for n in FIXTURE_NAMES: t = t.replace(n, '')
    return bool(re.search('[\u0600-\u06FF]{2,}', t))
def routes(rs, pred): return sorted({r['route'] for r in rs if pred(r)})
METRICS = {
  'loads': lambda r: True,
  'v3 gate NOT applied on the page': lambda r: not r['_ui'].startswith('legacy') and r.get('ui') != '3',
  'navigation error': lambda r: bool(r.get('navErr')),
  # a failed axe run is not "zero violations": surface it so the route/config is re-run, never read as clean
  'axe scan failed': lambda r: any(v.get('id') == 'axe-error' for v in r.get('axe') or []),
  'HTTP ≥ 400 (document)': lambda r: (r.get('status') or 0) >= 400,
  'page overflow-x > 0': lambda r: (r.get('overflowX') or 0) > 0,
  'h1 count ≠ 1': lambda r: r.get('h1', 1) != 1,
  'heading level skips': lambda r: (r.get('headingSkips') or 0) > 0,
  'console/page errors': lambda r: bool(r.get('consoleErrors')),
  'API ≥ 400 during load': lambda r: bool(r.get('failedApi')),
  'API 5xx during load': lambda r: any(f.startswith('5') for f in r.get('failedApi') or []),
  'missing messages': lambda r: bool(r.get('missingMessages')),
  'raw i18n keys': lambda r: bool(r.get('rawKeys')),
  'unnamed buttons/links': lambda r: (r.get('unnamed') or 0) > 0,
  'targets < 24px': lambda r: (r.get('small') or 0) > 0,
  'content leaving viewport': lambda r: (r.get('offscreen') or 0) > 0,
  # Excludes the language switch («ع», Arabic by design) and the exact fixture user/branch names shown in the topbar
  # (tenant data, not chrome); what remains must still hold two consecutive Arabic letters (drops the avatar initial).
  'Arabic chrome while EN': lambda r: r['cfg'].startswith('en') and any(arabic_left(t) for t in (r.get('arabicChrome') or [])),
}
rules = defaultdict(lambda: defaultdict(set))
for c, rs in by.items():
    for r in rs:
        for v in r.get('axe') or []:
            if v['id'] != 'axe-error': rules[v['id']][c].add(r['route'])
with open(out, 'w', encoding='utf-8') as f:
    f.write('# AWJ-ERP-UI-H2 A1 — Baseline crawl matrix (generated)\n\n')
    f.write('Generated by `tools/summarize_crawl.py` from `crawl.cjs` JSONL (H1 crawler, unchanged; axe-core 4.10.2). '
            'Values are **routes affected**. Local isolated backend, seed data only.\n\n')
    hdr = ' | '.join(f'{u} {c}' for u, c in cols)
    f.write(f'| Metric | {hdr} |\n|' + '---|' * (len(cols) + 1) + '\n')
    for name, pred in METRICS.items():
        f.write(f'| {name} | ' + ' | '.join(str(len(routes(by[c], pred))) for c in cols) + ' |\n')
    for rid in sorted(rules, key=lambda k: -sum(len(v) for v in rules[k].values())):
        f.write(f'| axe `{rid}` | ' + ' | '.join(str(len(rules[rid].get(c, ()))) for c in cols) + ' |\n')
    f.write('\n## Routes per finding (every column with a count above 0)\n\n')
    # the v3 desktop column: first non-legacy ar-light-1440 column, whatever its label
    main = next((c for c in cols if c[1] == 'ar-light-1440' and not c[0].startswith('legacy')), None)
    for name, pred in METRICS.items():
        if name == 'loads': continue
        for c in cols:
            rs = routes(by[c], pred)
            if rs: f.write(f'- **{name}** · {c[0]} {c[1]} ({len(rs)}): ' + ', '.join(f'`{x}`' for x in rs[:40]) + (' …' if len(rs) > 40 else '') + '\n')
    for rid in sorted(rules):
        for c in cols:
            rs = sorted(rules[rid].get(c, ()))
            if rs: f.write(f'- axe `{rid}` · {c[0]} {c[1]} ({len(rs)}): ' + ', '.join(f'`{x}`' for x in rs[:30]) + (' …' if len(rs) > 30 else '') + '\n')
    f.write('\n## API failures seen during load (v3 ar-light-1440)\n\n')
    agg = defaultdict(set)
    for r in by.get(main, []):
        for a in r.get('failedApi') or []: agg[a].add(r['route'])
    for a, rs in sorted(agg.items(), key=lambda kv: -len(kv[1])):
        f.write(f'- `{a}` on {len(rs)} route(s): ' + ', '.join(f'`{x}`' for x in sorted(rs)[:8]) + '\n')
