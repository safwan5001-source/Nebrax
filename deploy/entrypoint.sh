#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════
#  نقطة تشغيل حاوية نبراس (Production runtime)
#  تُهيّئ المفتاح، تُرحّل القاعدة، تُخزّن الإعداد، ثم تُقلع الخادم.
# ════════════════════════════════════════════════════════════════
set -euo pipefail

cd /app

# مفتاح التطبيق: يُضبط عبر env في المنصة. إن غاب نولّده لمنع فشل الإقلاع (مع تحذير).
if [ -z "${APP_KEY:-}" ]; then
  echo "⚠  APP_KEY غير مضبوط — أُولّد مفتاحاً مؤقتاً. للثبات اضبطه في متغيّرات البيئة."
  php artisan key:generate --force
fi

# تخزين الإعداد والمسارات (يسرّع الإقلاع؛ يتم الآن بعد توفّر متغيّرات البيئة).
# غير حاسم للإقلاع: إن فشل التخزين (مثلاً مسار closure) نُكمل بلا cache بدل إسقاط الخدمة.
php artisan config:cache || echo "⚠ config:cache تخطّي"
php artisan route:cache  || echo "⚠ route:cache تخطّي"

# ترحيل المخطط (immutable — يضيف الجداول الناقصة فقط)، مع إعادة محاولة
# لتفادي فشل الاتصال البارد بقاعدة مُدارة لحظة أول إقلاع.
echo "▶ ترحيل قاعدة البيانات..."
migrated=0
for attempt in 1 2 3 4 5; do
  if php artisan migrate --force; then
    migrated=1
    break
  fi
  # لا انتظار بعد المحاولة الأخيرة — الفشل محسوم، فلا تؤخّر ظهوره.
  if [ "${attempt}" -lt 5 ]; then
    echo "⚠ فشل الترحيل (محاولة ${attempt}/5) — إعادة بعد 5ث..."
    sleep 5
  fi
done

# ═══════════════════════════════════════════════════════════════
#  فشل الترحيل = فشل النشر. لا إقلاع بمخطّط قديم.
# ═══════════════════════════════════════════════════════════════
#  الإقلاع رغم فشل الترحيل يُنتج خدمةً «تعمل» بمخطّط ناقص: أخطاء ٥٠٠
#  متفرّقة وأرقاماً مبتورة بلا إنذار — وهو أخطر ما يصيب نظاماً محاسبياً،
#  لأنه يفشل صامتاً. الخروج بـ 1 يجعل المنصة تُعلن النشر فاشلاً وتُبقي
#  النسخة السابقة السليمة تخدم.
if [ "${migrated}" -ne 1 ]; then
  echo "✗ تعذّر ترحيل قاعدة البيانات بعد 5 محاولات — أوقفتُ الإقلاع عمداً."
  echo "  راجع سجلّ الترحيل أعلاه، ومتغيّرات DB_* واتصال القاعدة."
  exit 1
fi

# الخادم: PHP built-in خلف بروكسي المنصة على المنفذ المحقون
PORT="${PORT:-8000}"
echo "▶ إقلاع نبراس على المنفذ ${PORT}"
exec php artisan serve --host=0.0.0.0 --port="${PORT}"
