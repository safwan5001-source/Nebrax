#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════
#  نقطة تشغيل حاوية نبراس (Production runtime)
#  تُهيّئ المفتاح، تُرحّل القاعدة، تُخزّن الإعداد، ثم تُقلع الخادم.
# ════════════════════════════════════════════════════════════════
set -euo pipefail

cd /app

# مفتاح التطبيق: يُضبط عبر env في المنصة. إن غاب نولّده لمنع فشل الإقلاع (مع تحذير).
if [ -z "${APP_KEY:-}" ]; then
  echo "⚠  APP_KEY غير مضبوط — أُولّد مفتاحاً مؤقتاً. للثبات اضبطه في متغيّرات البيئة."
  php artisan key:generate --force
fi

# تخزين الإعداد والمسارات (يسرّع الإقلاع؛ يتم الآن بعد توفّر متغيّرات البيئة)
php artisan config:cache
php artisan route:cache

# انتظار قاعدة البيانات ثم ترحيل المخطط (immutable — يضيف الجداول الناقصة فقط)
echo "▶ ترحيل قاعدة البيانات..."
php artisan migrate --force

# الخادم: PHP built-in خلف بروكسي المنصة على المنفذ المحقون
PORT="${PORT:-8000}"
echo "▶ إقلاع نبراس على المنفذ ${PORT}"
exec php artisan serve --host=0.0.0.0 --port="${PORT}"
