// @vitest-environment jsdom
import { cleanup, fireEvent, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { ApiError } from '@/lib/api';
import { TEST_LOCALES, renderIntl, type TestLocale } from '@/test-utils/intl';
import { DOC_ID, blockedStatus, docReadyStatus, documentProjection, makeStatus } from '@/modules/intelligence/__tests__/fixtures';
import { api, canWith, resetSession, session } from './harness';

vi.mock('next/navigation', () => ({
  useRouter: () => ({ push: session.push, replace: vi.fn(), refresh: vi.fn() }),
  usePathname: () => session.pathname,
}));
vi.mock('@/lib/use-can', () => ({
  useCurrentUser: () => session.user,
  useCan: () => ({ can: canWith(session.user?.permissions ?? []), hydrated: true }),
}));
vi.mock('@/modules/intelligence/api', () => api);

import { IntelligenceProvider, useIntelligence } from '@/modules/intelligence/store';
import { AssistantPanel } from '../assistant-panel';
import { ConsentSettings } from '../consent-settings';
import { DocumentProjectionView } from '../document-result';

const run = () => ({ request_id: 'req-doc', status: 'ok' as const, tool_calls: [{ tool: 'documents.projected_read' as const, result: documentProjection() }] });

function Opener() {
  const { openPanel } = useIntelligence();
  return <button type="button" onClick={openPanel}>open-panel</button>;
}

function mountPanel(locale: TestLocale = 'en') {
  return renderIntl(<IntelligenceProvider locale={locale}><Opener /><AssistantPanel /></IntelligenceProvider>, locale);
}

async function openPanel() {
  await userEvent.click(screen.getByRole('button', { name: 'open-panel' }));
  return screen.findByRole('dialog');
}

beforeEach(() => {
  resetSession();
  session.pathname = `/documents/${DOC_ID}`;
});
afterEach(cleanup);

describe.each(TEST_LOCALES)('projection view (%s)', (locale) => {
  it('shows reviewed values, the basis and a Document Center link — and nothing else', () => {
    const { container } = renderIntl(<DocumentProjectionView projection={documentProjection()} />, locale);
    const text = container.textContent ?? '';
    expect(text).toContain('PI-2026-0042');
    expect(text).toContain('1,150.00');
    expect(text).toContain('صمام صناعي');
    expect(container.querySelector('[data-result="document_projection"]')).not.toBeNull();
    expect(screen.getByRole('link').getAttribute('href')).toBe(`/documents/${DOC_ID}`);
    expect(text).toContain(locale === 'ar' ? 'ليست من إنشاء المساعد' : 'not generated by the assistant');
    expect(text).toContain(locale === 'ar' ? 'لا يستطيع توجيه المساعد' : 'cannot instruct the assistant');
  });

  it('renders a redacted value as a label — the value itself is absent from the DOM', () => {
    const { container } = renderIntl(<DocumentProjectionView projection={documentProjection()} />, locale);
    expect(container.querySelectorAll('[data-redacted]')).toHaveLength(1);
    expect(screen.getAllByText(locale === 'ar' ? 'منقَّح' : 'Redacted').length).toBeGreaterThan(0);
  });

  it('treats document text as inert data: no markup, links, images or handlers are ever created from it', () => {
    const evil = '<img src=x onerror="window.__pwned=1"> <a href="javascript:alert(1)">click</a> [md](https://evil.example) <script>window.__pwned=2</script>';
    const projection = documentProjection({
      fields: [{ key: 'issuer_name', type: 'text', value: evil, redacted: false }],
      lines: [{ index: 0, fields: [{ key: 'description', type: 'text', value: evil, redacted: false }] }],
      warnings: [evil],
    });
    const { container } = renderIntl(<DocumentProjectionView projection={projection} />, locale);

    expect(container.querySelector('img')).toBeNull();
    expect(container.querySelector('script')).toBeNull();
    expect(container.querySelectorAll('a')).toHaveLength(1); // الرابط الوحيد: «فتح المستند» الداخلي
    expect(container.querySelector('a[href^="javascript:"]')).toBeNull();
    expect((window as unknown as { __pwned?: number }).__pwned).toBeUndefined();
    expect(container.textContent).toContain('<img src=x');
  });

  it('declares truncation instead of silently hiding data', () => {
    renderIntl(<DocumentProjectionView projection={documentProjection({ truncated: { fields: true, lines: true, warnings: true } })} />, locale);
    expect(screen.getByText(locale === 'ar' ? 'عُرضت الحقول الأولى فقط (حدّ العرض).' : 'Only the first fields are shown (display limit).')).toBeTruthy();
    expect(screen.getByText(locale === 'ar' ? 'عُرضت البنود الأولى فقط (حدّ العرض).' : 'Only the first lines are shown (display limit).')).toBeTruthy();
  });

  it('refuses to link an unsafe source path', () => {
    const projection = documentProjection({ sources: [{ type: 'document', service: 'DocumentCenter', ui_path: 'javascript:alert(1)' }] });
    renderIntl(<DocumentProjectionView projection={projection} />, locale);
    expect(screen.queryByRole('link')).toBeNull();
  });

  it('shows a non-SAR document in its own currency, never with the riyal sign', () => {
    const projection = documentProjection({
      fields: [
        { key: 'currency', type: 'text', value: 'USD', redacted: false },
        { key: 'total_amount_minor', type: 'money', value: 5000, decimal: '50.00', redacted: false },
      ],
      lines: [],
    });
    const { container } = renderIntl(<DocumentProjectionView projection={projection} />, locale);
    expect(container.textContent).toContain('50.00 USD');
    expect(container.textContent).not.toContain('⃁');
  });
});

describe('assistant panel on a document screen', () => {
  it('offers an explicit read and sends nothing until it is clicked; the id comes from the URL only', async () => {
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    api.readDocument.mockResolvedValue(run());
    mountPanel();
    const dialog = await openPanel();
    const read = await within(dialog).findByRole('button', { name: 'Read reviewed values' });
    expect(api.readDocument).not.toHaveBeenCalled();
    expect(within(dialog).getByText('Document review')).toBeTruthy(); // context chip

    await userEvent.click(read);
    await waitFor(() => expect(api.readDocument).toHaveBeenCalledTimes(1));
    expect(api.readDocument).toHaveBeenCalledWith(DOC_ID);
    await within(dialog).findByText('PI-2026-0042');
    expect(within(dialog).getByRole('button', { name: 'Refresh reading' })).toBeTruthy();
    expect(api.sendMessage).not.toHaveBeenCalled();
    expect(api.runTool).not.toHaveBeenCalled();
  });

  it.each(['consent_required', 'category_unavailable', 'document_center_unavailable', 'permission_denied', 'platform_disabled', 'tenant_disabled'] as const)(
    'shows the real state %s and no read button',
    async (state) => {
      api.fetchStatus.mockResolvedValue(makeStatus({ document: state, chat: state === 'permission_denied' ? 'permission_denied' : 'ready' }));
      mountPanel();
      const dialog = await openPanel();
      await waitFor(() => expect(dialog.querySelector(`[data-document-section] [data-notice="${state}"]`)).not.toBeNull());
      expect(within(dialog).queryByRole('button', { name: 'Read reviewed values' })).toBeNull();
      expect(api.readDocument).not.toHaveBeenCalled();
    },
  );

  it('maps a server refusal to its message with no content and no leak of why a hidden document exists', async () => {
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    api.readDocument.mockRejectedValue(new ApiError(404, 'x', { error: { code: 'document_unavailable', message: 'm' }, request_id: 'r' }));
    mountPanel();
    const dialog = await openPanel();
    await userEvent.click(await within(dialog).findByRole('button', { name: 'Read reviewed values' }));
    await waitFor(() => expect(dialog.querySelector('[data-notice="document_unavailable"]')).not.toBeNull());
    expect(dialog.querySelector('[data-result="document_projection"]')).toBeNull();
    // un bouton pour réessayer reste disponible: aucune relecture automatique
    expect(within(dialog).getByRole('button', { name: 'Read reviewed values' })).toBeTruthy();
  });

  it('hides a previous document’s content when the user moves to another document', async () => {
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    api.readDocument.mockResolvedValue(run());
    const { rerender } = mountPanel();
    const dialog = await openPanel();
    await userEvent.click(await within(dialog).findByRole('button', { name: 'Read reviewed values' }));
    await within(dialog).findByText('PI-2026-0042');

    session.pathname = '/documents/11111111-2222-4333-8444-555555555555';
    rerender(<IntelligenceProvider locale="en"><Opener /><AssistantPanel /></IntelligenceProvider>);
    await waitFor(() => expect(screen.queryByText('PI-2026-0042')).toBeNull());
  });

  it('does not show the document section on other screens', async () => {
    session.pathname = '/reports/general/income-statement';
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    mountPanel();
    const dialog = await openPanel();
    await within(dialog).findByRole('textbox');
    expect(dialog.querySelector('[data-document-section]')).toBeNull();
  });

  it('keeps the section accessible in Arabic', async () => {
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    mountPanel('ar');
    const dialog = await openPanel();
    expect(await within(dialog).findByRole('button', { name: 'قراءة القيم المراجَعة' })).toBeTruthy();
    expect(within(dialog).getByRole('region', { name: 'هذا المستند' })).toBeTruthy();
  });
});

describe('document category consent copy', () => {
  const settingsStatus = (overrides = {}) => docReadyStatus({
    tenant: { enabled: true, consented_categories: ['assistant_messages'] },
    categories: [
      { key: 'assistant_messages', available: true, consented: true },
      { key: 'financial_summary', available: true, consented: false },
      { key: 'document_projected_text', available: true, consented: false },
    ],
    document: 'consent_required',
    ...overrides,
  });

  it('presents distinct, document-specific opt-in copy and requires the acknowledgement', async () => {
    api.fetchStatus.mockResolvedValue(settingsStatus());
    api.saveSettings.mockResolvedValue(docReadyStatus());
    renderIntl(<IntelligenceProvider locale="en"><ConsentSettings /></IntelligenceProvider>, 'en');
    await userEvent.click(await screen.findByRole('switch', { name: /^Extracted document text/ }));

    const dialog = await screen.findByRole('dialog');
    expect(dialog.querySelector('[data-privacy="document"]')).not.toBeNull();
    expect(within(dialog).getByText('Document category privacy notice')).toBeTruthy();
    expect(within(dialog).getByText(/independent of “sending documents”/)).toBeTruthy();
    const confirm = within(dialog).getByRole('button', { name: 'Grant consent' }) as HTMLButtonElement;
    expect(confirm.disabled).toBe(true);
    await userEvent.click(within(dialog).getByRole('checkbox'));
    await userEvent.click(confirm);
    await waitFor(() => expect(api.saveSettings).toHaveBeenCalledWith({
      enabled: true, consented_categories: ['assistant_messages', 'document_projected_text'], acknowledge_privacy: true,
    }));
  });

  it('stays locked with an accurate label while the platform switch is closed', async () => {
    api.fetchStatus.mockResolvedValue(makeStatus());
    renderIntl(<IntelligenceProvider locale="en"><ConsentSettings /></IntelligenceProvider>, 'en');
    const doc = (await screen.findByRole('switch', { name: /^Extracted document text/ })) as HTMLButtonElement;
    expect(doc.disabled).toBe(true);
    expect(screen.getByText('Not enabled on the platform')).toBeTruthy();
  });

  it('revokes the document category immediately without an acknowledgement', async () => {
    api.fetchStatus.mockResolvedValue(docReadyStatus());
    api.saveSettings.mockResolvedValue(settingsStatus());
    renderIntl(<IntelligenceProvider locale="en"><ConsentSettings /></IntelligenceProvider>, 'en');
    await userEvent.click(await screen.findByRole('switch', { name: /^Extracted document text/ }));
    await waitFor(() => expect(api.saveSettings).toHaveBeenCalledWith({ enabled: true, consented_categories: ['assistant_messages', 'financial_summary'] }));
    expect(screen.queryByRole('dialog')).toBeNull();
    fireEvent.keyDown(document.body, { key: 'Escape' });
  });
});

