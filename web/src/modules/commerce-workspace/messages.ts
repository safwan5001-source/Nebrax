export type CommerceWorkspaceLocale = keyof typeof COMMERCE_WORKSPACE_MESSAGES;
export type CommerceWorkspaceMessageKey = keyof typeof COMMERCE_WORKSPACE_MESSAGES.ar;

export function commerceWorkspaceMessage(
  locale: string | undefined,
  key: CommerceWorkspaceMessageKey,
): string {
  const pack = locale?.startsWith('en') ? COMMERCE_WORKSPACE_MESSAGES.en : COMMERCE_WORKSPACE_MESSAGES.ar;
  return pack[key];
}
