export const COMMERCE_ORDERS_MESSAGES = { ar, en } as const;
export type OrdersMessageKey = keyof typeof ar;

export function ordersMessages(locale: string) {
  const dict: Record<OrdersMessageKey, string> = locale === 'en' ? en : ar;
  const t = (key: OrdersMessageKey): string => dict[key];
  /** يترجم قيمة خادم بمفتاح مسبوق؛ القيمة المجهولة تعود حرفياً. */
  const label = (prefix: 'status' | 'payment' | 'method' | 'delivery' | 'capture' | 'reason' | 'blocked' | 'cancelError' | 'acceptError' | 'acceptanceFilter' | 'acceptanceBadge' | 'acceptanceModeValue', value: string | null | undefined): string => {
    if (value === null || value === undefined || value === '') return '—';
    const key = `${prefix}.${value}` as OrdersMessageKey;
    return key in dict ? dict[key] : value;
  };
  return { t, label };
}
