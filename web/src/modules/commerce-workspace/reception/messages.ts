export const RECEPTION_MESSAGES = { ar, en } as const;
export type ReceptionMessageKey = keyof typeof ar;

export function receptionMessages(locale: string) {
  const dict: Record<ReceptionMessageKey, string> = locale === 'en' ? en : ar;
  const t = (key: ReceptionMessageKey, vars?: Record<string, string | number>): string => {
    let text = dict[key];
    for (const [k, v] of Object.entries(vars ?? {})) text = text.replace(`{${k}}`, String(v));

    return text;
  };

  return { t };
}
