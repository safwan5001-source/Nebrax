"""REM-18a — credit-note structure checks (BR-KSA-56 reference, BR-KSA-17 reason, PaymentMeansCode) and their
mutation controls. No SDK, no Java, no network, no keys: the XML is written out by hand, not generated by AWJ code."""
import os
import re
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import conformance as c  # noqa: E402

GOOD = """<?xml version="1.0" encoding="UTF-8"?>
<Invoice xmlns="urn:oasis:names:specification:ubl:schema:xsd:Invoice-2"
         xmlns:cac="urn:oasis:names:specification:ubl:schema:xsd:CommonAggregateComponents-2"
         xmlns:cbc="urn:oasis:names:specification:ubl:schema:xsd:CommonBasicComponents-2">
  <cbc:ID>SCN-1</cbc:ID>
  <cbc:InvoiceTypeCode name="0100000">381</cbc:InvoiceTypeCode>
  <cac:BillingReference>
    <cac:InvoiceDocumentReference>
      <cbc:ID>INV-1</cbc:ID>
    </cac:InvoiceDocumentReference>
  </cac:BillingReference>
  <cac:PaymentMeans>
    <cbc:PaymentMeansCode>10</cbc:PaymentMeansCode>
    <cbc:InstructionNote>Cancellation or suspension of the supplies after its occurrence</cbc:InstructionNote>
  </cac:PaymentMeans>
</Invoice>
"""


def problems(xml):
    return c.note_structure_problems(xml)


class NoteStructureTest(unittest.TestCase):
    def test_a_well_formed_credit_note_has_no_problems(self):
        self.assertEqual(problems(GOOD), [])

    def test_missing_billing_reference_is_flagged_even_though_the_sdk_only_warns(self):
        bad = re.sub(r"\s*<cac:BillingReference>.*?</cac:BillingReference>", "", GOOD, flags=re.S)
        self.assertTrue(any("BR-KSA-56" in p for p in problems(bad)))

    def test_empty_or_duplicated_billing_reference_is_flagged(self):
        self.assertTrue(any("BR-KSA-56" in p for p in problems(GOOD.replace("<cbc:ID>INV-1</cbc:ID>", "<cbc:ID> </cbc:ID>"))))
        ref = re.search(r"\s*<cac:BillingReference>.*?</cac:BillingReference>", GOOD, re.S).group(0)
        self.assertTrue(any("BR-KSA-56" in p for p in problems(GOOD.replace(ref, ref + ref))))

    def test_missing_or_blank_instruction_note_is_flagged(self):
        gone = re.sub(r"\s*<cbc:InstructionNote>.*?</cbc:InstructionNote>", "", GOOD, flags=re.S)
        self.assertTrue(any("BR-KSA-17" in p for p in problems(gone)))
        blank = re.sub(r"(<cbc:InstructionNote>).*?(</cbc:InstructionNote>)", r"\1  \2", GOOD, flags=re.S)
        self.assertTrue(any("BR-KSA-17" in p for p in problems(blank)))

    def test_missing_payment_means_is_flagged(self):
        gone = re.sub(r"\s*<cac:PaymentMeans>.*?</cac:PaymentMeans>", "", GOOD, flags=re.S)
        self.assertTrue(any("BR-KSA-17" in p for p in problems(gone)))

    def test_only_payment_means_code_10_is_accepted(self):
        for code in ("30", "42", "1", "99999", ""):
            self.assertTrue(any("PaymentMeansCode" in p for p in problems(
                GOOD.replace("<cbc:PaymentMeansCode>10<", f"<cbc:PaymentMeansCode>{code}<"))), code)

    def test_debit_notes_and_other_types_are_out_of_scope(self):
        for code in ("383", "388", "386"):
            self.assertTrue(any("InvoiceTypeCode" in p for p in problems(GOOD.replace(">381<", f">{code}<"))), code)

    def test_a_credit_note_root_is_not_accepted(self):
        bad = GOOD.replace("Invoice-2", "CreditNote-2").replace("<Invoice", "<CreditNote").replace("</Invoice>", "</CreditNote>")
        self.assertTrue(any("root element" in p for p in problems(bad)))

    def test_malformed_xml_is_reported_not_raised(self):
        self.assertTrue(any("not well-formed" in p for p in problems("<Invoice>")))


class NoteChecksTest(unittest.TestCase):
    def test_only_note_fixtures_are_checked_and_rows_carry_the_prefix(self):
        with tempfile.TemporaryDirectory() as d:
            note, other = os.path.join(d, "awj-note-a.xml"), os.path.join(d, "awj-standard-a.xml")
            for path, body in ((note, GOOD), (other, "<x/>")):
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(body)
            rows = c.note_checks([note, other], "signed/")
        self.assertEqual([(r["kind"], r["name"], r["verdict"]) for r in rows], [("note", "signed/awj-note-a.xml", "OK")])

    def test_a_bad_note_is_a_regression(self):
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "awj-note-a.xml")
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(GOOD.replace(">381<", ">383<"))
            rows = c.note_checks([path])
        self.assertEqual(rows[0]["verdict"], "REGRESSION")


class FakeRunner:
    """Behaves like a live SDK: BR-KSA-56 warning without BillingReference, BR-KSA-17 error without InstructionNote."""
    def __init__(self, live=True):
        self.live = live

    def validate(self, path):
        with open(path, "r", encoding="utf-8") as fh:
            body = fh.read()
        res = c.SdkResult(global_status="PASSED", stages={"KSA": "PASSED"}, errors={"KSA": []})
        if self.live and "<cac:BillingReference>" not in body:
            res.warnings.append("BR-KSA-56")
        if self.live and "<cbc:InstructionNote>" not in body:
            res.stages["KSA"], res.global_status = "FAILED", "FAILED"
            res.errors["KSA"].append("BR-KSA-17")
        return res


class NoteMutationLivenessTest(unittest.TestCase):
    def _run(self, runner, body=GOOD):
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "awj-note-a.xml")
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(body)
            return c.note_mutation_liveness(runner, [path], d)

    def test_a_live_oracle_passes(self):
        self.assertEqual(self._run(FakeRunner()), [])

    def test_a_silent_oracle_is_caught(self):
        out = self._run(FakeRunner(live=False))
        self.assertTrue(any("BR-KSA-56" in p for p in out) and any("BR-KSA-17" in p for p in out), out)

    def test_missing_fixture_is_a_problem(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertTrue(c.note_mutation_liveness(FakeRunner(), [], d))

    def test_a_fixture_already_missing_the_reference_is_caught(self):
        body = re.sub(r"\s*<cac:BillingReference>.*?</cac:BillingReference>", "", GOOD, flags=re.S)
        self.assertTrue(self._run(FakeRunner(), body))


